#include<iostream>
using namespace std;
int main(){
    int first, second;
    cout<<"Enter the first number: ";
    cin>>first;
    cout<<"Enter the second number: ";
    cin>>second;
    cout<<"Sum of the two numbers are : "<<first+second<<endl;
    cout<<"Difference of the two numbers are: "<<first-second<<endl;
    cout<<"Product of the two numbers are: "<<first*second<<endl;
    cout<<"Quotient of the two numbers are: "<<first/second;
}